CREATE TABLE IF NOT EXISTS clients (
  client_id VARCHAR(16) NOT NULL,
  realm VARCHAR(16) NOT NULL DEFAULT 'api',
  password VARCHAR(255) DEFAULT NULL,
  api_key VARCHAR(255) DEFAULT NULL,
  enc_key VARCHAR(255) NOT NULL,
  access TEXT DEFAULT NULL,
  is_active BOOLEAN DEFAULT TRUE,
  pwd_expiry TIMESTAMPTZ DEFAULT NULL,
  last_login BIGINT DEFAULT NULL,
  last_refresh BIGINT DEFAULT NULL,
  jti_refresh VARCHAR(64) DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ DEFAULT NULL,
  PRIMARY KEY (client_id, realm),
  UNIQUE (api_key)
);
